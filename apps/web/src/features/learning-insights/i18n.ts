export function useLearningInsightsT() {
  const lang = useLanguageStore((state) => state.lang);
  const value = messages[lang as keyof typeof messages] ?? messages.ru;
  const text = useCallback(
    (
      key: Exclude<keyof typeof value, 'status'>,
      params?: Record<string, string | number>,
    ) => String(value[key]).replace(/\{(\w+)\}/g, (_, name) => String(params?.[name] ?? `{${name}}`)),
    [value],
  );
  const status = useCallback(
    (key: keyof typeof value.status) => value.status[key],
    [value],
  );
  return { text, status };
}
