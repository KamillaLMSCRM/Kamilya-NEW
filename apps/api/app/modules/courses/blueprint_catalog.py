def get_blueprint(locale: str) -> dict[str, Any]:
    """Return a defensive copy of the finance IS blueprint for one locale."""
    if locale not in _LESSONS:
        raise KeyError(locale)
    meta = _LOCALIZED_META[locale]
    checklist = [
        {
            "id": item_id,
            "title": title,
            "description": description,
            "answer_placeholder": placeholder,
            "lesson_id": lesson_id,
            "required": True,
        }
        for item_id, title, description, placeholder, lesson_id in _CHECKLIST[locale]
    ]
    return deepcopy(
        {
            "id": FINANCE_IS_BLUEPRINT_ID,
            "version": FINANCE_IS_BLUEPRINT_VERSION,
            "locale": locale,
            **meta,
            "estimated_ready_percent": 70,
            "customization_percent": 30,
            "lessons": _LESSONS[locale],
            "checklist": checklist,
        }
    )


def list_blueprints(locale: str) -> list[dict[str, Any]]:
    return [get_blueprint(locale)]
