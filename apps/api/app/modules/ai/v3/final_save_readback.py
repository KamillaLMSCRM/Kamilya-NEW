"""Unwired strict V3 final-save snapshot comparison; not an ownership loader.

Only a trusted caller reading all rows under one owned snapshot may use this.
This module performs no database access and does not establish authorization,
transaction isolation, current source conversion or semantic course quality.
"""
from __future__ import annotations

import hashlib
from typing import Any

from app.modules.ai.v3.final_save_contract import (
    INTENT_KEY,
    RECEIPT_KEY,
    SOURCE_FIRST_KEYS,
    _validated_intent,
    output_digest,
)
from app.modules.ai.v3.pending_stage_transactions import has_pending


def _matches(row: Any, **expected: Any) -> bool:
    return all(getattr(row, key, object()) == value for key, value in expected.items())


def _ids_unique(rows: list[Any]) -> bool:
    ids = [getattr(row, "id", None) for row in rows]
    return all(value is not None for value in ids) and len(set(ids)) == len(ids)


def verify_snapshot(*, state: Any, intent: dict[str, Any], job: Any, course: Any,
                    source_corpus: Any, documents: list[Any], modules: list[Any], lessons: list[Any],
                    quizzes: list[Any], questions: list[Any], choices: list[Any]) -> bool:
    """Compare every V3 save row; caller owns and locks a complete snapshot.

    This compares only the MCQ-only projection generated by V3. Unsupported,
    incomplete, duplicate, foreign, or modified input returns False.
    """
    try:
        from app.modules.ai.pipeline import (
            _completed_progress_detail,
            _estimate_lesson_duration_seconds,
            _generation_completion_message,
        )
        from app.modules.ai.qa_luna_dev_route import QA_TENANT
        from app.modules.courses.source_uncertainty import preserve_generated_source_uncertainty

        _validated_intent(intent)
        tenant, user, job_id = intent["tenant_id"], intent["user_id"], intent["job_id"]
        if (tenant != str(QA_TENANT) or state.job_id != job_id
                or str(job.id) != job_id or str(job.tenant_id) != tenant or str(job.user_id) != user
                or job.status != "completed" or job.stage != "completed" or job.progress != 100
                or job.message != _generation_completion_message(state.content)
                or job.completed_at is None or job.updated_at != job.completed_at
                or job.errors not in (None, []) or str(job.course_id) != str(course.id)
                or str(course.tenant_id) != tenant or str(course.created_by) != user
                or has_pending(job.result) or not isinstance(job.result, dict)):
            return False
        if (job.result.get("delivery_task_id") != intent["delivery_id"] or INTENT_KEY in job.result
                or any(key in job.result for key in SOURCE_FIRST_KEYS)):
            return False
        receipt = job.result.get(RECEIPT_KEY)
        if (not isinstance(receipt, dict) or receipt != {"policy": "v3-final-save-receipt-v1",
                "intent_digest": intent["intent_digest"], "attempt_id": intent["attempt_id"],
                "course_id": str(course.id), "output_digest": intent["output_digest"]}):
            return False
        params = job.params if isinstance(job.params, dict) else {}
        analysis = params.get("source_analysis")
        if params.get("progress_detail") != _completed_progress_detail(state.content) or "completion" in params:
            return False
        if (not isinstance(analysis, dict) or analysis.get("generation_engine") != "evidence_v3"
                or analysis.get("analysis_mode") != "direct_source"
                or analysis.get("qa_luna_pending_journal_policy") != intent["route_policy"]
                or params.get("documents") != [doc["doc_id"] for doc in intent["documents"]]
                or state.source_document_ids != params.get("documents")):
            return False
        if len(documents) != len(intent["documents"]) or not _ids_unique(documents):
            return False
        by_doc = {str(doc.id): doc for doc in documents}
        if (str(source_corpus.tenant_id) != tenant
                or tuple(source_corpus.document_ids) != tuple(doc["doc_id"] for doc in intent["documents"])):
            return False
        converted = {doc.doc_id: doc for doc in source_corpus.documents}
        if len(converted) != len(intent["documents"]):
            return False
        for expected_doc in intent["documents"]:
            converted_doc = converted.get(expected_doc["doc_id"])
            if (converted_doc is None or converted_doc.source_revision != expected_doc["revision"]
                    or not isinstance(converted_doc.source_text, str)
                    or hashlib.sha256(converted_doc.source_text.encode("utf-8")).hexdigest() != expected_doc["text_sha256"]):
                return False
            doc = by_doc.get(expected_doc["doc_id"])
            if (doc is None or str(doc.tenant_id) != tenant or doc.lifecycle_status != "active"
                    or "document:" + str(doc.content_sha256) != expected_doc["revision"]):
                return False
        actual_digest = output_digest(structure=state.structure, content=state.content, assessment=state.assessment,
            source_document_ids=state.source_document_ids, source_strategy=state.source_strategy,
            source_combination_goal=state.source_combination_goal, source_analysis=state.source_analysis,
            source_review_required=state.server_source_review_required, reuse_reason=state.reuse_reason)
        if actual_digest != intent["output_digest"]:
            return False
        expected_analysis = preserve_generated_source_uncertainty({}, (
            {**state.source_analysis, "reuse_reason": state.reuse_reason} if state.reuse_reason else state.source_analysis
        ), source_review_required=state.server_source_review_required)
        if not _matches(course, title=state.structure.title, description=state.structure.description,
                        status="draft", delivery_type="native", review_status="pending", reviewed_by=None,
                        reviewed_at=None, review_comment=None, ai_generated=True, source_document_ids=state.source_document_ids,
                        source_strategy=state.source_strategy,
                        source_combination_goal=state.source_combination_goal or None,
                        source_analysis=expected_analysis):
            return False
        if any(not _ids_unique(rows) for rows in (modules, lessons, quizzes, questions, choices)):
            return False
        if (len(modules) != len(state.structure.modules) or len(state.content.modules) != len(modules)
                or len(lessons) != sum(len(mod.lessons) for mod in state.structure.modules)):
            return False
        ordered_modules = sorted(modules, key=lambda row: row.order_index)
        assessment_index = 0
        used_quizzes, used_questions, used_choices = set(), set(), set()
        for mi, (module, sm, cm) in enumerate(zip(ordered_modules, state.structure.modules, state.content.modules, strict=True)):
            if (str(module.tenant_id) != tenant or module.course_id != course.id
                    or not _matches(module, order_index=mi, title=sm.title, description=sm.description or "", ai_generated=True)):
                return False
            children = sorted((row for row in lessons if row.module_id == module.id), key=lambda row: row.order_index)
            if len(children) != len(sm.lessons) or len(cm.lessons) != len(sm.lessons):
                return False
            for li, (row, sl, cl) in enumerate(zip(children, sm.lessons, cm.lessons, strict=True)):
                if assessment_index >= len(state.assessment.assessments):
                    return False
                assessment = state.assessment.assessments[assessment_index]
                assessment_index += 1
                if (assessment.lesson_title != sl.title or assessment.true_false or assessment.matching
                        or any(q.supporting_source_evidence is not None for q in assessment.mcq)):
                    return False
                doc_ids = list(dict.fromkeys(str(ref.get("doc_id")) for ref in cl.source_references if ref.get("doc_id")))
                if (str(row.tenant_id) != tenant or not _matches(row, order_index=li, title=sl.title,
                        content_type="text", content=cl.content, ai_generated=True, published_at=None, source_document_ids=doc_ids,
                        source_references=cl.source_references,
                        duration_seconds=_estimate_lesson_duration_seconds(cl.content, len(assessment.mcq)),
                        source_validation_status="needs_review" if cl.requires_source_review() else "verified")):
                    return False
                qzs = [q for q in quizzes if q.lesson_id == row.id]
                if not assessment.mcq:
                    if qzs:
                        return False
                    continue
                if len(qzs) != 1:
                    return False
                quiz = qzs[0]
                used_quizzes.add(quiz.id)
                if (str(quiz.tenant_id) != tenant or not _matches(quiz, title=sl.title, pass_score=80, attempt_limit=3,
                        time_limit=None, deferral_days=7, review_status="needs_review", reviewed_by=None, reviewed_at=None)):
                    return False
                qrows = sorted((q for q in questions if q.quiz_id == quiz.id), key=lambda q: q.order_index)
                if len(qrows) != len(assessment.mcq):
                    return False
                for qi, (qr, expected) in enumerate(zip(qrows, assessment.mcq, strict=True)):
                    used_questions.add(qr.id)
                    if not _matches(qr, order_index=qi, text=expected.question, type="MCQ", points=1,
                                    explanation=expected.explanation, source_quote=expected.source_quote or None,
                                    pool_group=expected.pool_group):
                        return False
                    crows = sorted((c for c in choices if c.question_id == qr.id), key=lambda c: c.order_index)
                    if len(crows) != len(expected.options):
                        return False
                    correct = [option for option in expected.options if option.is_correct]
                    ordered = [option for option in expected.options if not option.is_correct]
                    if len(correct) == 1:
                        ordered.insert(qi % len(expected.options), correct[0])
                    else:
                        ordered = list(expected.options)
                    for ci, (cr, option) in enumerate(zip(crows, ordered, strict=True)):
                        used_choices.add(cr.id)
                        if not _matches(cr, order_index=ci, text=option.text, is_correct=option.is_correct):
                            return False
        return (assessment_index == len(state.assessment.assessments) and len(used_quizzes) == len(quizzes)
                and len(used_questions) == len(questions) and len(used_choices) == len(choices))
    except (AttributeError, TypeError, ValueError, KeyError):
        return False
