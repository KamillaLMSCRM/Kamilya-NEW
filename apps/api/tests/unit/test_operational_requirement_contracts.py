from __future__ import annotations

import pytest

from app.modules.ai.evidence_engine.operational_requirements import (
    SourceRequirementContract,
    project_source_requirement,
)


def test_projects_compound_exclusion_and_additional_negative_without_losing_scope() -> None:
    source = (
        "Расположение электрических кабелей и различных проводов должно исключать "
        "их повреждение, поражение работников электрическим током, а также они не "
        "должны мешать передвижению по помещению."
    )

    contract = project_source_requirement(source)

    assert isinstance(contract, SourceRequirementContract)
    assert contract.kind == "compound_exclusion_with_additional_negative"
    assert contract.source_scope == (
        "Расположение электрических кабелей и различных проводов"
    )
    assert contract.required_components == (
        "должно исключать их повреждение",
        "поражение работников электрическим током",
        "они не должны мешать передвижению по помещению",
    )
    assert "кабелей и различных проводов" in contract.required_prompt
    assert "Какие последствия нужно исключить" in contract.required_prompt
    assert "для объекта «Расположение" in contract.required_prompt


def test_projects_all_scope_provisioning_with_exact_emergency_purpose() -> None:
    source = (
        "Все помещения офисного здания ломбарда оснащаются планами эвакуации, "
        "в соответствии с которыми в случае пожара и других чрезвычайных ситуаций "
        "обеспечивается организованная эвакуация персонала."
    )

    contract = project_source_requirement(source)

    assert isinstance(contract, SourceRequirementContract)
    assert contract.kind == "all_scope_provisioning_with_purpose"
    assert contract.source_scope == "Все помещения офисного здания ломбарда"
    assert contract.required_components == (
        "оснащаются планами эвакуации",
        "в соответствии с которыми в случае пожара и других чрезвычайных ситуаций "
        "обеспечивается организованная эвакуация персонала",
    )
    assert "в каких случаях" in contract.required_prompt
    assert "для объектов «помещения офисного здания ломбарда»" in contract.required_prompt
    assert "Все помещения" not in contract.required_prompt


